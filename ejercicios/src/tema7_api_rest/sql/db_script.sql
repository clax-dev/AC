-- db_script.sql
-- Tablas de seguridad para la API de clientes (PostgreSQL, base de datos "basededatos").
-- Requiere que ya existan cliente, persona, empresa y pedido (postgres_basededatos.sql).
-- Se puede ejecutar varias veces: borra y vuelve a crear las tres tablas.

CREATE EXTENSION IF NOT EXISTS pgcrypto;   -- para generar los hashes BCrypt

DROP TABLE IF EXISTS client_permission;
DROP TABLE IF EXISTS usuario;
DROP TABLE IF EXISTS rol;

CREATE TABLE rol (
                     id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                     tipo_rol  VARCHAR(20) NOT NULL UNIQUE
                         CHECK (tipo_rol IN ('ADMIN', 'USER'))
);

CREATE TABLE usuario (
                         id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         id_rol         BIGINT NOT NULL,
                         usuario_login  VARCHAR(50) NOT NULL UNIQUE,
                         contrasena     VARCHAR(60) NOT NULL,

                         CONSTRAINT fk_usuario_rol
                             FOREIGN KEY (id_rol)
                                 REFERENCES rol (id)
                                 ON UPDATE CASCADE
                                 ON DELETE RESTRICT
);

CREATE TABLE client_permission (
                                   id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   usuario         VARCHAR(50) NOT NULL,
                                   codigo_cliente  VARCHAR(20) NOT NULL,
                                   permiso         VARCHAR(10) NOT NULL DEFAULT 'READ'
                                       CHECK (permiso IN ('READ')),

                                   CONSTRAINT uq_client_permission
                                       UNIQUE (usuario, codigo_cliente, permiso),

                                   CONSTRAINT fk_permission_usuario
                                       FOREIGN KEY (usuario)
                                           REFERENCES usuario (usuario_login)
                                           ON UPDATE CASCADE
                                           ON DELETE CASCADE,

                                   CONSTRAINT fk_permission_cliente
                                       FOREIGN KEY (codigo_cliente)
                                           REFERENCES cliente (codigo)
                                           ON UPDATE CASCADE
                                           ON DELETE CASCADE
);

